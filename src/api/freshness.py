# Mirrors src/market_calendar.py::get_market_session and the ``session`` field
# already returned by /api/market/quote. Kept identical on purpose — a second
# session vocabulary inside the same API would be worse than none.
SESSION_PRE_MARKET = "pre-market"
SESSION_REGULAR = "regular"
SESSION_AFTER_HOURS = "after-hours"
SESSION_CLOSED = "closed"


class FreshnessStatus(str, Enum):
    """The rolled-up freshness verdict for one response.

    ``fresh``
        ``source_timestamp`` is within one expected update cadence.
    ``aging``
        Past one cadence but not yet past ``stale_after`` — the grace band
        that absorbs normal cycle jitter.  Not an error; a client that
        polls faster than the cadence sees this routinely.
    ``stale``
        Past ``stale_after`` while updates *were* expected.  This is the
        actionable state: the feed behind this endpoint is late.
    ``session_closed``
        A feed-backed endpoint whose feed is not due to produce anything
        right now (weekend, holiday, or a feed that only runs during the
        session).  The payload is the last good value — deliberately NOT
        reported as ``stale``, because an overnight consumer polling a
        closed market is not observing a fault and should not page on it.
    ``static``
        The endpoint is not feed-backed at all: completed history, or a
        result computed from the caller's own inputs.  Age here carries no
        health meaning and never becomes a fault.
    ``unknown``
        No source timestamp could be resolved from the payload (e.g. a
        pure calculator, an admin endpoint, or an empty result set).  A
        consumer should fall back to ``evaluated_at`` for endpoint health
        and make no claim about data age.
    """

    FRESH = "fresh"
    AGING = "aging"
    STALE = "stale"
    SESSION_CLOSED = "session_closed"
    STATIC = "static"
    UNKNOWN = "unknown"


