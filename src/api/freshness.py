@dataclass(frozen=True)
class CadenceProfile:
    """How often one class of endpoint is expected to produce new data.

    Cadence is session-dependent, which is exactly why
    ``market_session_status`` rides in the envelope: advertising "60 s" at
    03:00 on a Sunday would be a lie, and a consumer that alerted on it
    would page every weekend.

    ``closed_seconds`` is the cadence on a **weekday** outside the feed
    window (04:00–20:00 ET).  For anything derived from the market feed it
    is ``None``: ingestion stops when after-hours closes at 20:00 ET and
    resumes at 04:00, so no new observation can land in between and an
    ageing payload is the correct answer rather than a late one.  A
    non-``None`` value here means "this artifact really is still being
    produced overnight".  Weekends and NYSE holidays always resolve to "no
    updates expected" regardless of this field.

    ``stale_grace`` / ``stale_floor_seconds`` set how far past the cadence
    a payload may drift before it is called ``stale``.  Both exist because
    a pure multiplier is wrong at both ends of the range: 3x a 1 s cadence
    is too tight to survive one slow cycle, and 3x a 300 s cadence is
    needlessly loose.  ``stale_after`` = source + max(cadence x grace,
    floor).
    """

    name: str
    description: str
    regular_seconds: Optional[float]
    extended_seconds: Optional[float]
    closed_seconds: Optional[float]
    # False for classes that are not backed by a live feed at all (completed
    # history, caller-supplied calculators). They report ``static`` rather
    # than ``session_closed``: "this never goes stale" and "the market is
    # shut" are different facts and a consumer alerts on them differently.
    feed_backed: bool = True
    # True for artifacts produced once per trading session. Their age is
    # measured in SESSIONS, not wall-clock seconds: Friday's close is still
    # the correct answer all through Monday morning, and a flat wall-clock
    # window reported ``stale`` every Monday and after every holiday.
    session_scoped: bool = False
    stale_grace: float = 2.5
    stale_floor_seconds: float = 15.0

    def cadence_for(self, session: str, *, market_day: bool) -> Optional[float]:
        """Expected cadence in this session, or ``None`` if no updates are due.

        ``market_day`` is False on weekends and NYSE holidays; nothing
        upstream changes then, so every profile reports "no updates
        expected" and the status becomes ``session_closed``.
        """
        if not market_day:
            return None
        if session == SESSION_REGULAR:
            return self.regular_seconds
        if session in (SESSION_PRE_MARKET, SESSION_AFTER_HOURS):
            return self.extended_seconds
        return self.closed_seconds

    def stale_window(self, cadence_seconds: float) -> float:
        """Seconds past ``source_timestamp`` before the payload is stale."""
        return max(cadence_seconds * self.stale_grace, self.stale_floor_seconds)


