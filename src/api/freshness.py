"""The v2 freshness envelope — endpoint health, evaluation time and data age
as three separately machine-readable concepts.

Every ``/api/v2/*`` response is wrapped as::

    {"data": <the v1 payload, unchanged>, "freshness": {...}}

and the ``freshness`` block answers the questions a consumer previously had
to reverse-engineer from whichever ad-hoc ``timestamp`` field an endpoint
happened to carry:

``evaluated_at``
    When the API evaluated *this response*.  Server wall clock, always
    present.  This is an **endpoint-health** signal: it advances on every
    request even when the underlying data is frozen, so a client can tell
    "the API answered me just now" apart from "the data is current".

``generated_at``
    When the served data was *computed*.  For snapshot-backed endpoints
    (the ~60 s analytics cycle) this is the snapshot's own stamp; for
    endpoints computed on demand for this request it equals
    ``evaluated_at``.

``source_timestamp``
    The stamp of the upstream market data the payload is derived from —
    the quote/snapshot instant, not the compute instant.  This is the
    **data-freshness** signal, and the one ``freshness_status`` is
    computed against.

``latest_event_at``
    The newest event timestamp actually present in the payload.  For a
    time series this is the last bar/row; for a single snapshot it usually
    equals ``source_timestamp``.  Best-effort (see ``_scan_timestamps``).

``market_session_status``
    ``pre-market`` | ``regular`` | ``after-hours`` | ``closed`` — the same
    four-value taxonomy the ``session`` field on ``/api/market/quote``
    already uses, deliberately not a second competing vocabulary.

``expected_update_cadence`` / ``expected_update_cadence_seconds``
    How often this endpoint's data is expected to change *right now*, as
    an ISO-8601 duration and as a number.  Session-dependent: the
    analytics cycle is 60 s during the cash session and 300 s off-hours.
    ``null`` means **no updates are expected** (a weekend, a holiday, or a
    feed that only runs during the session) — the served value is the last
    good one, not a stalled one.

``stale_after``
    The instant after which this payload should be treated as stale.
    Published so a consumer can set its own timer instead of guessing a
    threshold.  ``null`` whenever ``expected_update_cadence`` is ``null``.

``freshness_status``
    The rolled-up verdict — see :class:`FreshnessStatus`.

Why the cadence is a registry rather than a per-handler argument: the v2
surface is generated by mirroring every v1 route (see ``src/api/v2.py``),
so cadence has to be resolvable from the request path alone.  The registry
below is the single place an operator changes when a feed's cadence
changes, and every entry cites the config constant it mirrors.
"""

