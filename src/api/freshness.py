# Endpoints with no registry entry fall back to this. ON_DEMAND is the safe
# default: it makes no freshness claim it cannot support, so a newly added
# route is never mislabelled ``fresh``. A startup audit (see
# ``audit_cadence_coverage``) logs anything that lands here.
DEFAULT_PROFILE = ON_DEMAND


def resolve_profile(path: str) -> CadenceProfile:
    """Return the cadence profile registered for a **v1** API path."""
    for pattern, profile in ENDPOINT_CADENCE:
        if fnmatch.fnmatchcase(path, pattern):
            return profile
    return DEFAULT_PROFILE


def audit_cadence_coverage(paths: Iterable[str]) -> list[str]:
    """Return the paths that fell through to :data:`DEFAULT_PROFILE`.

    Called at startup by the v2 mirror so a route added without a registry
    entry shows up in the log instead of silently reporting ``unknown``
    freshness forever.
    """
    return [p for p in paths if not any(fnmatch.fnmatchcase(p, pat) for pat, _ in ENDPOINT_CADENCE)]


