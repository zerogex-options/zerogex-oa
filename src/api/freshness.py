DataT = TypeVar("DataT")


class Envelope(BaseModel, Generic[DataT]):
    """``{"data": <v1 payload>, "freshness": {...}}`` — the v2 response shape.

    ``data`` is byte-for-byte the v1 payload, including whatever event
    timestamps it already carried.  The envelope adds a parallel view; it
    never rewrites or removes a field, so migrating from v1 to v2 is
    "unwrap ``data``" and nothing else.
    """

    data: DataT
    freshness: Freshness


def _iso_duration(seconds: float) -> str:
    """Render seconds as an ISO-8601 duration (``PT60S`` / ``PT1H``).

    Whole hours and minutes are rendered as such because that is what a
    human reads in the docs; anything else stays in seconds rather than
    inventing a mixed representation.
    """
    if seconds >= 3600 and seconds % 3600 == 0:
        return f"PT{int(seconds // 3600)}H"
    if seconds >= 60 and seconds % 60 == 0:
        return f"PT{int(seconds // 60)}M"
    if seconds == int(seconds):
        return f"PT{int(seconds)}S"
    return f"PT{seconds:g}S"


def build_freshness(
    payload: Any,
    *,
    profile: CadenceProfile,
    now: Optional[datetime] = None,
    symbol: Optional[str] = None,
) -> Freshness:
    """Compute the freshness envelope for one response payload.

    Never raises: a freshness block is metadata about a response that has
    already been produced, so a failure to characterise it must not turn a
    good 200 into a 500.  Anything unexpected degrades to
    ``FreshnessStatus.UNKNOWN``.
    """
    evaluated_at = now or datetime.now(timezone.utc)
    # ES/NQ keep their own calendar; everything else is graded on NYSE cash.
    if _is_futures(symbol):
        session, market_day = futures_context(evaluated_at)
    else:
        session, market_day = market_context(evaluated_at)

    try:
        generated_at, latest_event_at = _scan_timestamps(payload, evaluated_at)
    except Exception:  # noqa: BLE001 - metadata must never break the response
        logger.warning("freshness: payload scan failed", exc_info=True)
        generated_at, latest_event_at = None, None

    # source_timestamp is the upstream observation. When a payload carries only
    # a computation stamp (a snapshot with no row-level stamps) that stamp is
    # the best available proxy — but ONLY if it describes an earlier
    # computation. A handler that stamps datetime.now() as it builds the
    # response (e.g. /api/news/headlines) would otherwise report age_seconds
    # ~0 and `fresh` forever, including during a total upstream outage that
    # returned zero items. A stamp minted during this request measures the
    # request, not the data, so it is not evidence of freshness.
    source_timestamp = latest_event_at
    if source_timestamp is None and generated_at is not None:
        minted_now = (evaluated_at - generated_at).total_seconds() < _REQUEST_TIME_STAMP_SECONDS
        source_timestamp = None if minted_now else generated_at
    age_seconds = (
        round((evaluated_at - source_timestamp).total_seconds(), 3) if source_timestamp else None
    )

    cadence_seconds = profile.cadence_for(session, market_day=market_day)
    stale_after: Optional[datetime] = None
    if cadence_seconds is not None and source_timestamp is not None:
        if profile.session_scoped:
            # Due when the NEXT trading session's artifact should exist, plus
            # the grace floor — so a Friday artifact is not "late" until well
            # after Monday's close.
            stale_after = next_session_close_after(source_timestamp) + timedelta(
                seconds=profile.stale_floor_seconds
            )
        else:
            # Never start the clock before the window that could produce the
            # next observation actually opened (see feed_window_open).
            window_open = feed_window_open(profile, evaluated_at)
            anchor = source_timestamp
            if window_open is not None and window_open > anchor:
                anchor = window_open
            stale_after = anchor + timedelta(seconds=profile.stale_window(cadence_seconds))

    if source_timestamp is None:
        status = FreshnessStatus.UNKNOWN
    elif cadence_seconds is None:
        # No update was due, so an old value is correct rather than late.
        status = FreshnessStatus.SESSION_CLOSED if profile.feed_backed else FreshnessStatus.STATIC
    elif profile.session_scoped:
        # Session-scoped artifacts are fresh right up to their stale_after;
        # there is no meaningful "aging" band between two daily deliveries.
        status = (
            FreshnessStatus.FRESH
            if stale_after is not None and evaluated_at <= stale_after
            else FreshnessStatus.STALE
        )
    elif age_seconds is not None and age_seconds <= cadence_seconds:
        status = FreshnessStatus.FRESH
    elif stale_after is not None and evaluated_at <= stale_after:
        status = FreshnessStatus.AGING
    else:
        status = FreshnessStatus.STALE

    return Freshness(
        evaluated_at=evaluated_at,
        # An endpoint that computes its answer for this request has no
        # separate generation instant — the evaluation IS the generation.
        generated_at=generated_at or evaluated_at,
        source_timestamp=source_timestamp,
        latest_event_at=latest_event_at,
        age_seconds=age_seconds,
        market_session_status=session,
        expected_update_cadence=(
            _iso_duration(cadence_seconds) if cadence_seconds is not None else None
        ),
        expected_update_cadence_seconds=cadence_seconds,
        cadence_profile=profile.name,
        stale_after=stale_after,
        freshness_status=status,
    )
